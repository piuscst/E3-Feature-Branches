portrait.append(face);

spin.addEventListener("click", () => {
  // Restart rather than accumulate simultaneous animations on repeated clicks.
  for (const animation of face.getAnimations()) animation.cancel();
  face.animate(
    [{ transform: "rotate(0deg)" }, { transform: "rotate(360deg)" }],
    { duration: 800, easing: "ease-in-out" },
  );
});

const starPoints =
  "0,-6 1.47,-2.02 5.71,-1.85 2.38,0.77 3.53,4.85 0,2.5 -3.53,4.85 -2.38,0.77 -5.71,-1.85 -1.47,-2.02";

for (let i = 0; i < 120; i++) {
  const angle = Math.random() * Math.PI * 2;
  const radius = 80 * Math.sqrt(Math.random());
  const star = document.createElementNS(
    "http://www.w3.org/2000/svg",
    "polygon",
  );
  star.setAttribute("points", starPoints);
  star.setAttribute(
    "transform",
    `translate(${100 + radius * Math.cos(angle)} ${
      100 + radius * Math.sin(angle)
    })`,
  );
  star.setAttribute("fill", "#f5c542");
  face.append(star);
}
